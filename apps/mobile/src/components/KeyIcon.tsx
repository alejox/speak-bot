import type { KeyIconId } from "@speed-deck/core";
import {
  ArrowLeft,
  ArrowRight,
  Bell,
  Captions,
  CaptionsOff,
  Check,
  CircleDot,
  CircleHelp,
  Clapperboard,
  Clock,
  Coffee,
  Droplet,
  Eraser,
  Eye,
  EyeOff,
  FileText,
  Folder,
  Hand,
  Heart,
  Languages,
  LayoutGrid,
  MessageSquare,
  Mic,
  MicOff,
  Headphones,
  Music,
  Radio,
  Repeat,
  Smile,
  Square,
  Star,
  X,
  type LucideIcon,
} from "lucide-react";

/** The drawing of every key icon id (Lucide, ISC license). */
const ICONS: Record<KeyIconId, LucideIcon> = {
  message: MessageSquare,
  stop: Square,
  repeat: Repeat,
  language: Languages,
  eraser: Eraser,
  captions: Captions,
  "captions-off": CaptionsOff,
  "arrow-left": ArrowLeft,
  "arrow-right": ArrowRight,
  page: FileText,
  board: LayoutGrid,
  scene: Clapperboard,
  mic: Mic,
  "mic-off": MicOff,
  headphones: Headphones,
  broadcast: Radio,
  record: CircleDot,
  eye: Eye,
  "eye-off": EyeOff,
  heart: Heart,
  hand: Hand,
  check: Check,
  cross: X,
  question: CircleHelp,
  star: Star,
  smile: Smile,
  water: Droplet,
  coffee: Coffee,
  clock: Clock,
  bell: Bell,
  music: Music,
  folder: Folder,
};

/** A decorative key icon; unknown ids draw nothing. */
export function KeyIcon({ id, size = 28 }: { id: string; size?: number }) {
  const Icon = ICONS[id as KeyIconId];
  return Icon ? <Icon className="key-icon" size={size} strokeWidth={2} aria-hidden="true" focusable="false" /> : null;
}
